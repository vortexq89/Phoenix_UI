local _, ns = ...
local M = ns:GetModule("Encounters")

--[[ Boss modules (BigWigs / LittleWigs parity, t201): every raid and dungeon of every expansion, read from the
    game's Encounter Journal through the shared core reader ns.Journal (Core/Journal.lua), and per-ability
    choices for each boss: hide, emphasise, sound or count-in on the timeline bars (Bars.lua). Choices are
    stored per spell ID in timeline.abilities; data defaults come from ns.EncounterData (Data.lua). ]]

local J = ns.Journal
M.HasJournal = J.Has

-- Option lists ({ value, label }) over the core reader.
function M.JournalTiers()
    local out = {}
    for _, t in ipairs(J.Tiers()) do out[#out + 1] = { value = t.tier, label = t.name } end
    return out
end
function M.JournalInstances(tier, raid)
    local out = {}
    if not tier then return out end
    for _, i in ipairs(J.Instances(raid, tier)) do out[#out + 1] = { value = i.id, label = i.name } end
    return out
end
function M.JournalBosses(instanceID)
    local out = {}
    if not instanceID then return out end
    for _, b in ipairs(J.Bosses(instanceID)) do out[#out + 1] = { value = b.id, label = b.name } end
    return out
end
function M.BossAbilities(encounterID)
    local out = {}
    if not encounterID then return out end
    for _, a in ipairs(J.Abilities(encounterID)) do out[#out + 1] = { value = a.spellID, label = a.name } end
    return out
end

-- The data entry for a spell in any encounter (ns.EncounterData, generated by tools/sync/boss_data.py), or nil.
local byspell
local function dataFor(spellID)
    if not byspell then
        byspell = {}
        local data = ns.EncounterData and ns.EncounterData.encounters or {}
        for _, abilities in pairs(data) do
            for id, a in pairs(abilities) do if type(a) == "table" then byspell[id] = a end end
        end
    end
    return byspell[spellID]
end
function M.DataDefault(spellID)
    local a = dataFor(spellID)
    return a and a.default
end
function M.DataRole(spellID)
    local a = dataFor(spellID)
    return a and a.role
end

-- Your current role ("TANK" / "HEALER" / "DAMAGER"), from your spec, else the group role; nil when unknown.
local function myRole()
    local r
    local SI = C_SpecializationInfo
    if SI and SI.GetSpecialization and GetSpecializationRole then
        local spec = SI.GetSpecialization()
        if spec then r = GetSpecializationRole(spec) end
    end
    if (r == nil or r == "NONE") and UnitGroupRolesAssigned then r = UnitGroupRolesAssigned("player") end
    if r == "NONE" then return nil end
    return r
end
M.MyRole = myRole

-- True when the data says the ability matters only to a role you are not playing (BigWigs' role options):
-- tank abilities for non-tanks, healer ones for non-healers, tank_healer ones for damage dealers.
local OTHER = {
    tank = function(r) return r ~= "TANK" end,
    healer = function(r) return r ~= "HEALER" end,
    tank_healer = function(r) return r == "DAMAGER" end,
}
function M.ForOtherRole(spellID)
    local test = OTHER[M.DataRole(spellID) or "all"]
    local r = test and myRole()
    return r ~= nil and test(r) or false
end

M.CHOICES = { default = true, hide = true, emph = true, sound = true, count = true }
function M:SetAbilityChoice(spellID, what)
    if type(spellID) ~= "number" or not M.CHOICES[what] then return false end
    local t = self.db.timeline
    t.abilities = type(t.abilities) == "table" and t.abilities or {}
    t.abilities[spellID] = what ~= "default" and what or nil
    return true
end
function M:AbilityChoice(spellID)
    local t = self.db.timeline.abilities
    return type(t) == "table" and t[spellID] or "default"
end
