#!/usr/bin/env python3
"""Builds Modules/Minimap/RevealData.lua: the WoW Forever world map overlays (the pieces of a zone map that stay
dark until you explore them), from the client's own DB2 tables on wago.tools (product wowf):
  WorldMapOverlay      ID, UiMapArtID, TextureWidth, TextureHeight, OffsetX, OffsetY, ...
  WorldMapOverlayTile  RowIndex, ColIndex, LayerIndex, FileDataID, WorldMapOverlayID
Only game data is shipped (art IDs, sizes, offsets, texture file IDs); the Lua that draws it is Phoenix's own.

  python3 tools/mapreveal/build.py            # download the current wowf build and rewrite the data file
  python3 tools/mapreveal/build.py DIR        # use WorldMapOverlay.csv / WorldMapOverlayTile.csv from DIR
"""
import collections
import csv
import io
import json
import pathlib
import sys
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent.parent
OUT = ROOT / "Modules" / "Minimap" / "RevealData.lua"
BRANCH = "wowf"


def request(url):
    return urllib.request.Request(url, headers={"User-Agent": "Phoenix_UI-mapreveal"})


def fetch(name, src):
    if src:
        return (pathlib.Path(src) / f"{name}.csv").read_text(encoding="utf-8")
    url = f"https://wago.tools/db2/{name}/csv?branch={BRANCH}"
    with urllib.request.urlopen(request(url), timeout=120) as r:
        return r.read().decode("utf-8")


def build_version():
    try:
        with urllib.request.urlopen(request("https://wago.tools/api/builds"), timeout=60) as r:
            return json.load(r)[BRANCH][0]["version"]
    except Exception:  # noqa: BLE001 - the version is a label only
        return "unknown"


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else None
    overlays = list(csv.DictReader(io.StringIO(fetch("WorldMapOverlay", src))))
    tiles = collections.defaultdict(list)
    for t in csv.DictReader(io.StringIO(fetch("WorldMapOverlayTile", src))):
        if t["LayerIndex"] == "0":
            tiles[t["WorldMapOverlayID"]].append((int(t["RowIndex"]), int(t["ColIndex"]), int(t["FileDataID"])))
    arts = collections.defaultdict(list)
    for o in overlays:
        if o["PlayerConditionID"] != "0":
            continue  # shown only to some players (phases, quests): the game decides those
        ts = sorted(tiles.get(o["ID"], []))
        if not ts or any(f <= 0 for _, _, f in ts):
            continue
        cols = max(c for _, c, _ in ts) + 1
        rows = max(r for r, _, _ in ts) + 1
        if len(ts) != cols * rows:
            continue  # a hole in the tile grid: skip rather than draw it wrong
        arts[int(o["UiMapArtID"])].append("%s,%s,%s,%s,%d,%s" % (o["TextureWidth"], o["TextureHeight"], o["OffsetX"],
                                          o["OffsetY"], cols, ".".join(str(f) for _, _, f in ts)))
    version = build_version() if not src else "local csv"
    lines = ["-- World map overlays for WoW Forever (map reveal). Generated by tools/mapreveal/build.py from the client's",
             "-- WorldMapOverlay / WorldMapOverlayTile DB2 tables (wago.tools, %s %s); do not edit." % (BRANCH, version),
             "-- Per map art ID: one string per overlay, 'width,height,offsetX,offsetY,columns,fileID.fileID...'.",
             "local _, ns = ...",
             "if ns.flavor ~= \"forever\" then return end -- these are Forever's overlays; retail never builds the table",
             "ns.RevealData = {",
             '    build = "%s",' % version,
             "    arts = {"]
    for art in sorted(arts):
        lines.append("        [%d] = {" % art)
        lines += ['            "%s",' % o for o in arts[art]]
        lines.append("        },")
    lines += ["    },", "}", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(arts)} map arts, {sum(len(v) for v in arts.values())} overlays")


if __name__ == "__main__":
    main()
