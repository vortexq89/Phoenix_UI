#!/usr/bin/env python3
"""Builds Phoenix_UI_Encounters/Data.lua (ns.EncounterData) from the public BigWigs / LittleWigs module files.

Only facts are taken: per boss, its Encounter Journal ID and the spell IDs it has options for, with the role
and emphasis flags those options carry. No code is copied; the output is Phoenix's own format (see Data.lua).
The daily sync reruns this:  python3 tools/sync/boss_data.py <dir with the cloned repos> [out]
Repos: BigWigsMods/BigWigs, LittleWigs and BigWigs_<Expansion> (clone with --depth 1). """
import datetime, os, re, sys

NEWBOSS = re.compile(r'NewBoss\(\s*"((?:[^"\\]|\\.)*)"\s*,\s*(-?\d+)\s*,\s*(\d+)')
ENTRY = re.compile(r'^\s*(\{\s*)?(\d+)\s*(?:,([^}\n]*))?\}?\s*,')
FLAGS = re.compile(r'"([A-Z_]+)"')
ROLE = {"TANK": "tank", "HEALER": "healer", "TANK_HEALER": "tank_healer", "DISPEL": "healer"}
DEFAULT = {"EMPHASIZE": "emph", "ME_ONLY_EMPHASIZE": "emph", "COUNTDOWN": "count"}


def parse(path):
    text = open(path, encoding="utf-8", errors="replace").read()
    m = NEWBOSS.search(text)
    if not m:
        return None
    name, journal = m.group(1), int(m.group(3))
    start = text.find("function mod:GetOptions()")
    if journal <= 0 or start < 0:
        return None
    body = text[start:]
    end = re.search(r"\n end\b|\nend\b", body)
    body = body[: end.start()] if end else body
    spells = {}
    for line in body.splitlines():
        e = ENTRY.match(line)
        if not e:
            continue
        spell, flags = int(e.group(2)), FLAGS.findall(e.group(3) or "")
        role = next((ROLE[f] for f in flags if f in ROLE), "all")
        default = next((DEFAULT[f] for f in flags if f in DEFAULT), None)
        spells[spell] = (role, default)
    return journal, name, spells


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else "/workspace/bwsrc"
    out = sys.argv[2] if len(sys.argv) > 2 else "Phoenix_UI_Encounters/Data.lua"
    bosses = {}
    for root, _, files in os.walk(src):
        if "/Libs" in root or "/.git" in root:
            continue
        for f in sorted(files):
            if f.endswith(".lua"):
                r = parse(os.path.join(root, f))
                if r and r[2]:
                    journal, name, spells = r
                    bosses.setdefault(journal, [name, {}])[1].update(spells)
    lines = [
        "-- © 2026 VortexQ8 / ABDULRAHMAN ALYOUSEF. Phoenix UI. All rights reserved.",
        "local _, ns = ...",
        "",
        "--[[ Phoenix boss knowledge, per encounter, every expansion. GENERATED by tools/sync/boss_data.py (the daily",
        "    sync reruns it); do not edit by hand. Facts only (journal encounter ID, ability spell IDs, the role and",
        "    emphasis each ability matters for), gathered from the public BigWigs / LittleWigs boss modules; the",
        "    encounter list, names and journal tree themselves come live from the game (Core/Journal.lua).",
        "",
        "    encounters[journalEncounterID] = { [spellID] = { role = \"all\"|\"tank\"|\"healer\"|\"tank_healer\",",
        "        default = \"emph\"|\"count\"|nil } }   -- default applies when you have not chosen one yourself",
        "    Your own choice (Encounters > Boss modules) always wins over a default here. ]]",
        "local E = {}",
    ]
    total = 0
    for journal in sorted(bosses):
        name, spells = bosses[journal]
        parts = []
        for spell in sorted(spells):
            role, default = spells[spell]
            d = ', default = "%s"' % default if default else ""
            parts.append('[%d] = { role = "%s"%s }' % (spell, role, d))
        total += len(parts)
        lines.append("-- %s" % name.replace("\\", ""))
        cur = "E[%d] = { " % journal
        for p in parts:
            if len(cur) + len(p) + 2 > 136:
                lines.append(cur.rstrip())
                cur = "    "
            cur += p + ", "
        lines.append(cur.rstrip() + " }" if cur.strip() else "}")
    lines += [
        "",
        "ns.EncounterData = {",
        "    schema = 1,",
        '    updated = "%s",' % datetime.date.today().isoformat(),
        "    encounters = E,",
        "}",
        "",
    ]
    open(out, "w", encoding="utf-8").write("\n".join(lines))
    print("boss_data: %d encounters, %d abilities -> %s" % (len(bosses), total, out))


if __name__ == "__main__":
    main()
