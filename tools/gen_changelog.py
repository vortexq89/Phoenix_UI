#!/usr/bin/env python3
# Writes Core/Changelog.lua (version headings and bold item titles) from CHANGES.md: python3 tools/gen_changelog.py CHANGES.md > Core/Changelog.lua
import re,sys
src=open(sys.argv[1]).read()
out=['local _, ns = ...','-- Generated by tools/gen_changelog.py from CHANGES.md: version headings and the bold item titles. Do not edit.','ns.CHANGELOG = {']
ver=None;items=[]
def flush():
    if ver: out.append('    { version = %s, items = {' % lua(ver)); out.extend('        %s,'%lua(i) for i in items); out.append('    } },')
def lua(s): return '"'+s.replace('\\','\\\\').replace('"','\\"')+'"'
for line in src.splitlines():
    m=re.match(r'^## (.+)',line)
    if m: flush(); ver=m.group(1).strip(); items=[]; continue
    m=re.match(r'^- \*\*(.+?)\*\*\s*(\([^)]*\))?:?\s*(.*)',line)
    if m and ver:
        t=m.group(1).strip(); rest=re.sub(r'[`*]','',m.group(3)); rest=re.split(r'(?<=[.;:])\s',rest)[0][:110]
        items.append((t+' — '+rest).rstrip(' —') if rest else t)
flush(); out.append('}'); print('\n'.join(out))
