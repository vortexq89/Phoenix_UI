#!/usr/bin/env python3
"""Rasterizes the Phoenix icon set (Phosphor duotone, MIT) and the Phoenix emblem/logo.

Outputs (run from the repo root: python3 tools/media/gen_icons.py):
  Media/Icons/Icons24.tga, Icons48.tga, Icons96.tga  atlas tiers (white glyphs, RLE TGA, power-of-two)
  Media/Icons/LICENSE                                Phosphor licence
  Media/Textures/Emblem64/128/256.tga, Logo512/1024.tga   coloured brand art
  Core/IconData.lua                                  generated manifest (names, tiers, cell geometry)
  docs/screenshots/assets/*.png                      PNG copies used by the HTML mockups
WoW does not mipmap addon TGAs, so each tier is pre-filtered and ns.Icons picks the smallest tier that is at
least as large as the on-screen size in physical pixels (never more than ~2x downsampling)."""
import io
import pathlib
import re
import shutil
import sys

import cairosvg
from PIL import Image, ImageDraw, ImageFilter, ImageFont

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from icon_map import ICONS  # noqa: E402

SRC = ROOT / "tools" / "media" / "phosphor"
ICON_OUT = ROOT / "Media" / "Icons"
TEX_OUT = ROOT / "Media" / "Textures"
DOC_OUT = ROOT / "docs" / "screenshots" / "assets"
COLS = 10
DUOTONE_ALPHA = 0.3  # Phosphor ships 0.2; slightly stronger so the fill reads at 16 px on dark panels
# Micro-control glyphs keep only the line layer: Phosphor's duotone fill for these is a solid box that reads as a
# checkbox behind a close "x" or a check mark.
LINE_ONLY = {"close", "check", "add", "chevron-right", "chevron-down", "chevron-left", "resize"}
TIERS = [(24, 1), (48, 2), (96, 3)]  # (cell px, gutter px per side)


def pow2(n):
    p = 1
    while p < n:
        p *= 2
    return p


def white_svg(name, line_only=False):
    svg = (SRC / f"{name}-duotone.svg").read_text(encoding="utf-8")
    svg = svg.replace('fill="currentColor"', 'fill="#ffffff"')
    if line_only:
        return re.sub(r'<(path|rect|circle|polygon)[^>]*opacity="0\.2"[^>]*/>', "", svg)
    return re.sub(r'opacity="0\.2"', f'opacity="{DUOTONE_ALPHA}"', svg)


def render(svg, size):
    png = cairosvg.svg2png(bytestring=svg.encode(), output_width=size, output_height=size)
    im = Image.open(io.BytesIO(png)).convert("RGBA")
    # pure white RGB everywhere (no dark fringes when tinted/filtered), alpha carries the glyph
    return Image.merge("RGBA", (Image.new("L", im.size, 255),) * 3 + (im.getchannel("A"),))


def save_tga(im, path):
    path.parent.mkdir(parents=True, exist_ok=True)
    im.save(path, compression="tga_rle")


def atlases():
    rows = (len(ICONS) + COLS - 1) // COLS
    tiers = []
    for cell, gutter in TIERS:
        w, h = pow2(COLS * cell), pow2(rows * cell)
        sheet = Image.new("RGBA", (w, h), (255, 255, 255, 0))
        for i, (name, glyph) in enumerate(ICONS):
            col, row = i % COLS, i // COLS
            glyph_im = render(white_svg(glyph, name in LINE_ONLY), cell - 2 * gutter)
            sheet.alpha_composite(glyph_im, (col * cell + gutter, row * cell + gutter))
        name = f"Icons{cell}"
        save_tga(sheet, ICON_OUT / f"{name}.tga")
        if cell == 96:
            sheet.save(DOC_OUT / "icons96.png")
        tiers.append({"file": name, "cell": cell, "gutter": gutter, "width": w, "height": h})
    return tiers


def write_manifest(tiers):
    lines = [
        "local _, ns = ...",
        "",
        "-- GENERATED by tools/media/gen_icons.py from tools/media/icon_map.py. Do not edit by hand.",
        "-- Glyphs: Phosphor Icons (duotone), MIT licence, see Media/Icons/LICENSE.",
        "ns.IconData = {",
        f"    cols = {COLS},",
        "    tiers = {",
    ]
    for t in tiers:
        lines.append(f'        {{ file = "{t["file"]}", cell = {t["cell"]}, gutter = {t["gutter"]}, '
                     f'width = {t["width"]}, height = {t["height"]} }},')
    lines += ["    },", "    index = {"]
    for i, (name, _) in enumerate(ICONS, start=1):
        lines.append(f'        ["{name}"] = {i},')
    lines += ["    },", "}", ""]
    (ROOT / "Core" / "IconData.lua").write_text("\n".join(lines), encoding="utf-8")


def fire_paths():
    svg = (SRC / "fire-duotone.svg").read_text(encoding="utf-8")
    return re.findall(r'<path d="([^"]+)"( opacity="0\.2")?/>', svg)


def emblem_svg():
    duo, line = [p for p, _ in fire_paths()]
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256">
<defs>
  <linearGradient id="rim" x1="0" y1="0" x2="1" y2="1">
    <stop offset="0" stop-color="#FFE0A0"/><stop offset="0.35" stop-color="#FFB23F"/>
    <stop offset="0.7" stop-color="#FF6A1A"/><stop offset="1" stop-color="#D93500"/></linearGradient>
  <radialGradient id="core" cx="0.5" cy="0.62" r="0.62">
    <stop offset="0" stop-color="#4A1E0C"/><stop offset="0.55" stop-color="#1D1013"/><stop offset="1" stop-color="#0E0F13"/></radialGradient>
  <linearGradient id="flame" x1="0" y1="1" x2="0" y2="0">
    <stop offset="0" stop-color="#FF4A0A"/><stop offset="0.5" stop-color="#FF8A2A"/><stop offset="1" stop-color="#FFE2A6"/></linearGradient>
</defs>
<rect x="53" y="53" width="150" height="150" rx="20" transform="rotate(45 128 128)" fill="url(#core)"/>
<rect x="53" y="53" width="150" height="150" rx="20" transform="rotate(45 128 128)" fill="none" stroke="url(#rim)" stroke-width="11"/>
<rect x="64" y="64" width="128" height="128" rx="13" transform="rotate(45 128 128)" fill="none"
      stroke="#FFFFFF" stroke-opacity="0.10" stroke-width="2"/>
<g transform="translate(128 134) scale(0.52) translate(-128 -128)">
  <path d="{duo}" fill="url(#flame)" opacity="0.55"/>
  <path d="{line}" fill="url(#flame)"/>
</g>
</svg>'''


def emblem(size):
    hi = size * 4
    png = cairosvg.svg2png(bytestring=emblem_svg().encode(), output_width=hi, output_height=hi)
    art = Image.open(io.BytesIO(png)).convert("RGBA")
    # soft ember glow behind the badge
    glow_mask = art.getchannel("A").filter(ImageFilter.GaussianBlur(hi / 32))
    glow = Image.new("RGBA", art.size, (255, 90, 16, 0))
    glow.putalpha(glow_mask.point(lambda a: int(a * 0.55)))
    out = Image.alpha_composite(glow, art)
    return out.resize((size, size), Image.LANCZOS)


def logo(width):
    h = width // 4
    im = Image.new("RGBA", (width * 2, h * 2), (0, 0, 0, 0))
    em = emblem(int(h * 2 * 0.94))
    im.alpha_composite(em, (int(h * 0.06), int(h * 0.06)))
    x0 = int(h * 2 * 1.1)
    fsize = int(h * 2 * 0.6)
    font_path = str(ROOT / "Media" / "Fonts" / "Cinzel-Bold.ttf")
    font = ImageFont.truetype(font_path, fsize)
    room = im.size[0] - x0 - int(h * 0.4)
    while font.getlength("PHOENIX") > room:  # fit the wordmark with a right margin
        fsize -= 2
        font = ImageFont.truetype(font_path, fsize)
    mask = Image.new("L", im.size, 0)
    ImageDraw.Draw(mask).text((x0, h * 2 * 0.5), "PHOENIX", font=font, fill=255, anchor="lm")
    grad = Image.new("RGBA", im.size)
    px = grad.load()
    for x in range(im.size[0]):
        t = max(0.0, min(1.0, (x - x0) / (im.size[0] - x0)))
        col = (255, int(122 + (196 - 122) * t), int(38 + (92 - 38) * t), 255)
        for y in range(im.size[1]):
            px[x, y] = col
    shadow = Image.new("RGBA", im.size, (0, 0, 0, 0))
    shadow.putalpha(mask.filter(ImageFilter.GaussianBlur(4)).point(lambda a: int(a * 0.6)))
    im = Image.alpha_composite(im, shadow)
    text = Image.new("RGBA", im.size, (0, 0, 0, 0))
    text.paste(grad, (0, 0), mask)
    im = Image.alpha_composite(im, text)
    return im.resize((width, h), Image.LANCZOS)


def brand():
    for size in (64, 128, 256):
        save_tga(emblem(size), TEX_OUT / f"Emblem{size}.tga")
    emblem(256).save(DOC_OUT / "emblem.png")
    for width in (512, 1024):
        save_tga(logo(width), TEX_OUT / f"Logo{width}.tga")
    logo(1024).save(DOC_OUT / "logo.png")


if __name__ == "__main__":
    DOC_OUT.mkdir(parents=True, exist_ok=True)
    ICON_OUT.mkdir(parents=True, exist_ok=True)
    shutil.copy(SRC / "LICENSE", ICON_OUT / "LICENSE")
    tiers = atlases()
    write_manifest(tiers)
    brand()
    total = sum(p.stat().st_size for p in list(ICON_OUT.glob("*.tga")) + list(TEX_OUT.glob("Emblem*.tga"))
                + list(TEX_OUT.glob("Logo*.tga")))
    print(f"{len(ICONS)} icons, tiers {[t['file'] for t in tiers]}, {total / 1024:.0f} KiB of TGA")
