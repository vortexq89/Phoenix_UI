#!/usr/bin/env python3
"""Emit Data/ApiManifest.lua and Data/SchemaIndex.lua (PUI_V2 16.9).

ApiManifest: every Blizzard API Phoenix calls, with the owning module(s),
checked against Data/ApiCatalog.json (live + forever). Sentinel's Drift check
reads it at login. SchemaIndex: every settings key -> module and file.

  python3 .tools/manifest.py          # write both files
  python3 .tools/manifest.py --check  # exit 1 if either file is stale
"""
import json, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import luascan

ROOT = luascan.ROOT
CATALOG = os.path.join(ROOT, "Data", "ApiCatalog.json")
GUARD = "local PUI = _G.PhoenixUI if not (PUI and PUI.gateOpen) then return end"

# Engine/FrameXML globals that Blizzard's generated docs do not list. Each one
# was checked against Gethe/wow-ui-source live 12.1.5 FrameXML usage or is a
# Lua 5.1 base/WoW-sandbox global.
ENGINE_GLOBALS = {
    "CreateFrame", "InCombatLockdown", "IsInGroup", "GetNumGroupMembers", "securecallfunction",
    "hooksecurefunc", "seterrorhandler", "geterrorhandler", "debugstack", "debuglocals",
    "wipe", "tinsert", "date", "time",
}

CALL_RE = re.compile(r"(?<![\w.:])([A-Za-z_]\w*)(?!\s*=[^=])(?!\w)")
LOCAL_RE = re.compile(r"\blocal\s+(?:function\s+)?([A-Za-z_][\w\s,]*)")
NS_RE = re.compile(r"(?<![\w.:])(C_\w+\.\w+)")


def load_catalog():
    with open(CATALOG, encoding="ascii") as fh:
        return json.load(fh)


def scan_apis(catalog):
    apis = catalog["apis"]
    found = {}
    for path in luascan.lua_files():
        r = luascan.rel(path)
        if r.startswith("Data/"):
            continue
        code = luascan.strip(open(path, encoding="utf-8").read())
        names = set(NS_RE.findall(code))
        local = set()
        for m in LOCAL_RE.finditer(code):
            local.update(x.strip() for x in m.group(1).split(",") if x.strip())
        for m in CALL_RE.finditer(code):
            name = m.group(1)
            if name in local:
                continue
            entry = apis.get(name)
            if name in ENGINE_GLOBALS or (entry and entry["type"] == "function" and entry["system"] not in WIDGET_SYSTEMS):
                names.add(name)
        for name in names:
            found.setdefault(name, set()).add(luascan.owner_of(r))
    return found


# Widget method docs (SimpleFrameAPI etc.) are listed without a namespace; a
# bare call to one of those names is a local helper, not a global API.
WIDGET_SYSTEMS = set()


def schema_index():
    keys = {}
    pat = re.compile(r'(?:Register|toggle)\(\s*"([a-z]+\.[A-Za-z0-9_.]+)"')
    for path in luascan.lua_files():
        r = luascan.rel(path)
        if r.startswith("Tests/") or r.startswith("Data/"):
            continue
        src = luascan.strip(open(path, encoding="utf-8").read(), keep_strings=True)
        for key in pat.findall(src):
            prefix = key.split(".")[0]
            module = {"core": "Core", "sentinel": "Sentinel"}.get(prefix, key.split(".")[1] if prefix == "module" else prefix)
            keys[key] = {"module": module, "file": r}
    return dict(sorted(keys.items()))


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render_manifest(found, catalog):
    apis = catalog["apis"]
    src = catalog["sources"]
    lines = [GUARD, "-- Generated by .tools/manifest.py from the source tree and Data/ApiCatalog.json. Do not edit.",
             "PUI.ApiManifest = {",
             "  catalog = { live = %s, ptr = %s, forever = %s }," % tuple(
                 lua_str(src.get(t, {}).get("build", "?")) for t in ("live", "ptr", "forever")),
             "  apis = {"]
    for name in sorted(found):
        owners = ", ".join(lua_str(o) for o in sorted(found[name]))
        entry = apis.get(name)
        flags = ""
        if entry and "forever" not in entry["in"]:
            flags = ", retailOnly = true"
        elif entry and "live" not in entry["in"]:
            flags = ", foreverOnly = true"
        lines.append("    [%s] = { owners = { %s }%s }," % (lua_str(name), owners, flags))
    lines += ["  },", "}", ""]
    return "\n".join(lines)


def render_schema(index):
    lines = [GUARD, "-- Generated by .tools/manifest.py: every settings key -> module and file. Do not edit.",
             "PUI.SchemaIndex = {"]
    for k, v in index.items():
        lines.append("  [%s] = { module = %s, file = %s }," % (lua_str(k), lua_str(v["module"]), lua_str(v["file"])))
    lines += ["}", ""]
    return "\n".join(lines)


def outputs():
    catalog = load_catalog()
    global WIDGET_SYSTEMS
    WIDGET_SYSTEMS = {e["system"] for e in catalog["apis"].values() if e["system"].startswith("Simple")}
    return {
        os.path.join(ROOT, "Data", "ApiManifest.lua"): render_manifest(scan_apis(catalog), catalog),
        os.path.join(ROOT, "Data", "SchemaIndex.lua"): render_schema(schema_index()),
    }


def main():
    check = "--check" in sys.argv
    stale = []
    for path, text in outputs().items():
        old = open(path, encoding="ascii").read() if os.path.exists(path) else None
        if old != text:
            stale.append(luascan.rel(path))
            if not check:
                with open(path, "w", encoding="ascii", newline="\n") as fh:
                    fh.write(text)
    if check and stale:
        print("stale generated files: " + ", ".join(stale) + " (run python3 .tools/manifest.py)")
        return 1
    print(("up to date" if not stale else "wrote " + ", ".join(stale)) if not check else "manifest up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
