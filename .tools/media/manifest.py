#!/usr/bin/env python3
"""Phoenix_UI_Media manifest.

  python3 .tools/media/manifest.py --merge a.json b.json ...  write manifest.json, Manifest.lua, LICENSES.md
  python3 .tools/media/manifest.py --check                     every media file has an entry and an allowed licence

manifest.json is the per-file record (file, type, name, source, author, licence, changes).
"""
import json, os, re, sys
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
CHILD = os.path.join(ROOT, "Phoenix_UI_Media")
MEDIA = os.path.join(CHILD, "Media")
MANIFEST = os.path.join(CHILD, "manifest.json")
ALLOWED = {"SIL OFL 1.1", "CC0 1.0", "CC BY 3.0", "CC BY 4.0", "MIT", "Apache 2.0", "Original (Phoenix UI)"}
EXT = {"font": (".ttf", ".otf"), "sound": (".ogg",), "statusbar": (".tga",), "background": (".tga",),
       "border": (".tga",), "glow": (".tga",), "icon": (".tga",), "moduleicon": (".tga",), "texture": (".tga",)}
KIND_ORDER = ["font", "statusbar", "background", "border", "glow", "icon", "moduleicon", "texture", "sound"]


def ascii_text(s):
    return s.encode("ascii", "replace").decode().replace("?", "") if s else s


def lua_str(s):
    return '"' + ascii_text(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_lua(entries):
    out = ["local PUI = _G.PhoenixUI if not (PUI and PUI.gateOpen) then return end",
           "-- Generated by .tools/media/manifest.py from manifest.json; do not edit.",
           "local R = PUI.Media.Register", "local M = PUI.Media", ""]
    for e in sorted(entries, key=lambda e: (KIND_ORDER.index(e["type"]), e["name"].lower())):
        path = "Interface\\\\AddOns\\\\Phoenix_UI_Media\\\\Media\\\\" + e["file"].replace("/", "\\\\")
        meta = "{ licence = %s%s }" % (lua_str(e["licence"]), (", coverage = " + lua_str(e["coverage"])) if e.get("coverage") else "")
        out.append('R(M, "%s", %s, "%s", %s)' % (e["type"], lua_str(e["name"]), path, meta))
    open(os.path.join(CHILD, "Manifest.lua"), "w", encoding="ascii").write("\n".join(out) + "\n")


def write_md(entries):
    by = {}
    for e in entries:
        by.setdefault(e["licence"], []).append(e)
    lines = ["# Phoenix_UI_Media licences", "",
             "Every file in Media/ is listed in manifest.json with its source, author and licence.",
             "Only SIL OFL, CC0, CC BY, MIT/Apache and original Phoenix UI work are accepted (checked in CI).", "",
             "Licence texts are in Licenses/.", "", "## Attribution", "",
             "- Fonts: Google Fonts contributors, SIL Open Font License 1.1 (Licenses/*-OFL.txt). Static instances were cut from variable fonts; names are unchanged.",
             "- Sounds: Kenney (www.kenney.nl), CC0 1.0.",
             "- Icons: Icons made by %s from game-icons.net, CC BY 3.0 (zeromancer: CC0). Rendered white on transparent." %
             ", ".join(sorted({e["author"] for e in entries if e["type"] == "icon"})),
             "- Bar textures, backgrounds, borders and glows: original procedural work for Phoenix UI (.tools/media/textures.py).",
             "- Phoenix design set (logo, module icons, ability preview icons, Phoenix statusbars, panels, nine-slices, controls, glows, overlays, hero and preset art, Phoenix_* sounds): original Phoenix UI work, All Rights Reserved; not licensed for reuse outside Phoenix UI.", ""]
    for lic in sorted(by):
        lines += ["## %s (%d files)" % (lic, len(by[lic])), "", "| File | Name | Author | Source |", "|---|---|---|---|"]
        for e in sorted(by[lic], key=lambda e: e["file"]):
            lines.append("| %s | %s | %s | %s |" % (e["file"], e["name"], ascii_text(e["author"]).replace("|", "/")[:80], e["source"]))
        lines.append("")
    open(os.path.join(CHILD, "LICENSES.md"), "w", encoding="ascii").write("\n".join(lines))


def check():
    problems = []
    entries = json.load(open(MANIFEST, encoding="utf-8"))
    listed = {}
    for e in entries:
        for k in ("file", "type", "name", "source", "author", "licence"):
            if not e.get(k):
                problems.append("%s: missing %s" % (e.get("file"), k))
        if e.get("licence") not in ALLOWED:
            problems.append("%s: licence not allowed: %s" % (e.get("file"), e.get("licence")))
        if not e["file"].lower().endswith(EXT.get(e.get("type"), ("?",))):
            problems.append("%s: wrong extension for %s" % (e["file"], e.get("type")))
        if not os.path.isfile(os.path.join(MEDIA, e["file"])):
            problems.append("%s: listed but missing" % e["file"])
        listed[e["file"]] = e
    for dp, _, fns in os.walk(MEDIA):
        for f in fns:
            rel = os.path.relpath(os.path.join(dp, f), MEDIA).replace(os.sep, "/")
            if rel not in listed:
                problems.append("%s: media file without a manifest entry" % rel)
            if rel.endswith(".tga"):
                with open(os.path.join(dp, f), "rb") as fh:
                    h = fh.read(18)
                w, hgt = h[12] | h[13] << 8, h[14] | h[15] << 8
                if w & (w - 1) or hgt & (hgt - 1):
                    problems.append("%s: %dx%d is not power-of-two" % (rel, w, hgt))
    lua = open(os.path.join(CHILD, "Manifest.lua"), encoding="ascii").read()
    if lua.count("\nR(M, ") != len(entries):
        problems.append("Manifest.lua is out of date (run with --merge)")
    return problems, entries


if __name__ == "__main__":
    if "--merge" in sys.argv:
        entries = []
        for p in sys.argv[sys.argv.index("--merge") + 1:]:
            entries += json.load(open(p, encoding="utf-8"))
        json.dump(entries, open(MANIFEST, "w", encoding="utf-8"), indent=1, ensure_ascii=False)
        write_lua(entries); write_md(entries)
    problems, entries = check()
    counts = {}
    for e in entries:
        counts[(e["type"], e["licence"])] = counts.get((e["type"], e["licence"]), 0) + 1
    for k in sorted(counts):
        print("  %-11s %-22s %d" % (k[0], k[1], counts[k]))
    for p in problems:
        print("  " + p)
    print("media manifest: %d files, %s" % (len(entries), "ok" if not problems else "%d problem(s)" % len(problems)))
    sys.exit(1 if problems else 0)
