import manifest as mm

ORIG, AUTHOR, SRC = "Original (Phoenix UI)", "Phoenix UI (VortexQ8)", "generated by .tools/media/gaps_art.py"
OUT = mm.MEDIA
entries = json.load(open(mm.MANIFEST, encoding="utf-8"))
have = {e["file"]: e for e in entries}


def add(rel, kind, name):
    e = dict(file=rel, type=kind, name=name, source=SRC, author=AUTHOR, licence=ORIG, changes="none")
    if rel in have: have[rel].update(e)
    else: entries.append(e); have[rel] = e


def render(svg, size):
    png = cairosvg.svg2png(bytestring=svg.encode(), output_width=size, output_height=size)
    return Image.open(io.BytesIO(png)).convert("RGBA")


def save(img, rel):
    p = os.path.join(OUT, rel); os.makedirs(os.path.dirname(p), exist_ok=True)
    img.save(p, compression=None)


def grey(img):
    px = img.load(); out = Image.new("RGBA", img.size); po = out.load()
    for y in range(img.size[1]):
        for x in range(img.size[0]):
            r, g, b, a = px[x, y]; v = int((0.299 * r + 0.587 * g + 0.114 * b) * 0.78)
            po[x, y] = (v, v, v, int(a * 0.85))
    return out


