# Original procedural textures for Phoenix UI (no third-party input).
import os, json, math, random
from PIL import Image, ImageFilter, ImageDraw
O="/workspace/media_out"; man=[]
def save(img,rel,name,typ):
  p=os.path.join(O,rel); os.makedirs(os.path.dirname(p),exist_ok=True)
  img.save(p,compression=None)  # uncompressed TGA (RLE off) for the client
  man.append({"file":rel,"type":typ,"name":name,"source":"generated by .tools/media/textures.py","author":"Phoenix UI (VortexQ8)","licence":"Original (Phoenix UI)","changes":"n/a"})
def grey(v): v=max(0,min(255,int(v))); return (v,v,v,255)
W,H=256,32
def bar(fn):
  im=Image.new("RGBA",(W,H)); px=im.load()
  for y in range(H):
    for x in range(W): px[x,y]=fn(x,y)
  return im
rnd=random.Random(7); noise=[[rnd.random() for _ in range(W)] for _ in range(H)]
t=lambda y:y/(H-1)
BARS={
 "Flat":lambda x,y:grey(255),
 "Gradient":lambda x,y:grey(255-90*t(y)),
 "Gradient Reverse":lambda x,y:grey(165+90*t(y)),
 "Gloss":lambda x,y:grey(255 if y<H*0.45 else 200-30*t(y)),
 "Smooth":lambda x,y:grey(205+50*math.sin(math.pi*t(y))),
 "Satin":lambda x,y:grey(180+75*math.cos(math.pi*(t(y)-0.3))**2),
 "Glass":lambda x,y:grey(250-40*t(y) if y<H/2 else 190+50*(t(y)-0.5)),
 "Beveled":lambda x,y:grey(255 if y<2 else (120 if y>=H-2 else 215)),
 "Inner Shadow":lambda x,y:grey(255-110*max(0,1-min(y,H-1-y)/6)),
 "Edge Light":lambda x,y:grey(255 if y<3 else 205),
 "Striped":lambda x,y:grey(255 if ((x+y)//6)%2==0 else 215),
 "Hatched":lambda x,y:grey(255 if ((x-y)//3)%4 else 175),
 "Ridged":lambda x,y:grey(235 if y%4<2 else 200),
 "Grain":lambda x,y:grey(215+40*noise[y][x]),
 "Grain Gradient":lambda x,y:grey(240-70*t(y)+25*noise[y][x]),
 "Halftone":lambda x,y:grey(255 if (x%6-3)**2+(y%6-3)**2>4 else 200),
 "Minimal Line":lambda x,y:grey(255 if y>=H-4 else 230),
 "Dual Tone":lambda x,y:grey(255 if y<H/2 else 205),
 "Soft Fade":lambda x,y:grey(255-150*abs(t(y)-0.5)**1.5),
 "Metal":lambda x,y:grey(200+35*math.sin(y*0.7)+20*noise[y][x]),
 "Pill":lambda x,y:grey(255-120*(2*t(y)-1)**4),
 "Scanline":lambda x,y:grey(255 if y%2 else 190),
}
for n,f in BARS.items(): save(bar(f),"Statusbar/"+n.replace(" ","")+".tga",n,"statusbar")
# Backgrounds 256x256 tileable
S=256; r2=random.Random(11)
def bg(fn):
  im=Image.new("RGBA",(S,S)); px=im.load()
  for y in range(S):
    for x in range(S): px[x,y]=fn(x,y)
  return im
nz=[[r2.random() for _ in range(S)] for _ in range(S)]
BG={
 "Solid":lambda x,y:grey(255),
 "Noise":lambda x,y:grey(225+30*nz[y][x]),
 "Carbon":lambda x,y:grey(170+70*(((x//4)+(y//4))%2)+15*((x+y)%4==0)),
 "Diagonal":lambda x,y:grey(255 if (x+y)%16<2 else 210),
 "Grid":lambda x,y:grey(255 if x%32==0 or y%32==0 else 215),
 "Dots":lambda x,y:grey(255 if (x%16-8)**2+(y%16-8)**2<5 else 215),
 "Checker":lambda x,y:grey(235 if ((x//32)+(y//32))%2 else 215),
 "Brushed":lambda x,y:grey(200+40*nz[y][0]+15*nz[y][x]),
 "Waves":lambda x,y:grey(220+30*math.sin(2*math.pi*(y+8*math.sin(2*math.pi*x/S))/32)),
 "Plaid":lambda x,y:grey(205+25*((x%64)<16)+25*((y%64)<16)),
}
for n,f in BG.items(): save(bg(f),"Background/"+n+".tga",n,"background")
# Hex background
im=Image.new("RGBA",(S,S),(215,215,215,255)); d=ImageDraw.Draw(im)
r=16; h=r*math.sqrt(3)
for row in range(-1,12):
  for col in range(-1,12):
    cx=col*1.5*r; cy=row*h+(h/2 if col%2 else 0)
    d.polygon([(cx+r*math.cos(math.pi/3*k),cy+r*math.sin(math.pi/3*k)) for k in range(6)],outline=(255,255,255,255))
save(im,"Background/Hex.tga","Hex","background")
# Vignette (not tileable, fills a frame)
im=bg(lambda x,y:grey(255-150*min(1,((x-128)**2+(y-128)**2)/(128**2)))); save(im,"Background/Vignette.tga","Vignette","background")
# Borders: backdrop edge files, 8 segments of e x e laid out horizontally (edge size e).
def edge(e,fill):
  seg=Image.new("RGBA",(e,e),(0,0,0,0)); fill(seg,e)
  corner=seg.copy()
  im=Image.new("RGBA",(e*8,e),(0,0,0,0))
  # left, right, top, bottom edges then 4 corners (WoW backdrop order)
  L=seg; R=seg.transpose(Image.FLIP_LEFT_RIGHT); T=seg.rotate(-90); B=seg.rotate(90)
  for i,p in enumerate([L,R,T,B,corner,corner.transpose(Image.FLIP_LEFT_RIGHT),corner.transpose(Image.FLIP_TOP_BOTTOM),corner.rotate(180)]):
    im.paste(p,(i*e,0))
  return im
def line(w,soft=False,double=False):
  def f(seg,e):
    px=seg.load()
    for y in range(e):
      for x in range(e):
        a=255 if x<w else 0
        if double and w+2<=x<w+3: a=255
        if soft and a==0: a=int(255*max(0,1-(x-w+1)/(e-w)))**1
        px[x,y]=(255,255,255,a)
  return f
for n,e,f in [("Pixel 1px",8,line(1)),("Pixel 2px",8,line(2)),("Thick 3px",16,line(3)),("Double Line",16,line(1,double=True)),("Soft Edge",16,line(1,soft=True)),("Glow Edge",32,line(0,soft=True))]:
  save(edge(e,f),"Border/"+n.replace(" ","")+".tga",n,"border")
# Glows / shapes 64x64 or 128x128 white with alpha
def shape(sz,fa):
  im=Image.new("RGBA",(sz,sz)); px=im.load(); c=(sz-1)/2
  for y in range(sz):
    for x in range(sz):
      dx,dy=(x-c)/c,(y-c)/c; px[x,y]=(255,255,255,max(0,min(255,int(255*fa(dx,dy)))))
  return im
GL={
 "Soft Circle":(64,lambda dx,dy:max(0,1-math.hypot(dx,dy))**1.6),
 "Hard Circle":(64,lambda dx,dy:1 if math.hypot(dx,dy)<0.95 else 0),
 "Ring":(64,lambda dx,dy:max(0,1-abs(math.hypot(dx,dy)-0.8)*8)),
 "Ring Glow":(128,lambda dx,dy:max(0,1-abs(math.hypot(dx,dy)-0.75)*4)**2),
 "Square Glow":(64,lambda dx,dy:max(0,1-max(abs(dx),abs(dy)))**1.2),
 "Spark":(64,lambda dx,dy:max(0,1-math.hypot(dx,dy))**3+max(0,1-abs(dx)*12)*max(0,1-abs(dy))+max(0,1-abs(dy)*12)*max(0,1-abs(dx))),
 "Star Burst":(128,lambda dx,dy:max(0,1-math.hypot(dx,dy))**2*(0.6+0.4*math.cos(8*math.atan2(dy,dx)))),
 "Diamond":(64,lambda dx,dy:1 if abs(dx)+abs(dy)<0.95 else 0),
 "Fade Horizontal":(64,lambda dx,dy:(dx+1)/2),
 "Fade Vertical":(64,lambda dx,dy:(1-dy)/2),
 "Corner Shadow":(64,lambda dx,dy:max(0,1-math.hypot(dx+1,dy+1)/2)),
 "Highlight":(64,lambda dx,dy:max(0,1-abs(dy))*0.7),
}
for n,(sz,f) in GL.items(): save(shape(sz,f),"Glow/"+n.replace(" ","")+".tga",n,"glow")
