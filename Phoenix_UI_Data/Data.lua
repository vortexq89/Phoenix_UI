local _, D = ...

--[[ Phoenix_UI_Data: quest-giver positions, prerequisites and turn-in areas for Phoenix UI's Quests module.
    Load-on-demand; Phoenix loads it when quest pins are switched on. Each Quests_<Slice>.lua is generated by
    tools/questdata/build_questdata.py and only fills its slice on the game it belongs to (retail or WoW
    Forever), so one file list serves both clients. Provenance and licences: README.md, LICENSE-ATT.txt. ]]
local INTERFACE = select(4, GetBuildInfo())
D.flavor = (type(INTERFACE) == "number" and INTERFACE >= 16000 and INTERFACE < 20000) and "forever" or "retail"
D.quests, D.npcNames, D.questNames, D.slices = {}, {}, {}, {}
-- NPC positions per slice (NPCs_<Slice>.lua) and the merged local recordings (NPCs_Collected.lua)
D.npcs, D.collected, D.vignettes = {}, {}, {}

-- True when a slice belongs to this client; records it with its expansion for the expansion filter.
function D:Slice(key, flavor, expansion)
    if flavor ~= self.flavor then return false end
    self.slices[#self.slices + 1] = { key = key, expansion = expansion }
    return true
end

-- True when a slice's companion file (NPCs_<Slice>.lua) belongs to this client and its quest slice loaded.
function D:Owns(key, flavor)
    if flavor ~= self.flavor then return false end
    for _, s in ipairs(self.slices) do if s.key == key then return true end end
    return false
end

-- Positions merged from the local collector (tools/questdata/merge_collected.py): no names, realms or GUIDs.
function D:Collected(flavor, npcs, vignettes)
    if flavor ~= self.flavor then return end
    for mapID, packed in pairs(npcs or {}) do self.collected[mapID] = packed end
    for id, spot in pairs(vignettes or {}) do self.vignettes[id] = spot end
end

-- English NPC and quest names from the source DB (the game's own localized quest title is preferred).
function D:Names(_, npcs, quests)
    for id, name in pairs(npcs) do self.npcNames[id] = name end
    for id, name in pairs(quests) do self.questNames[id] = name end
end

PhoenixUI_QuestData = D
