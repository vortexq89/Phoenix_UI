local PUI = _G.PhoenixUI if not (PUI and PUI.gateOpen) then return end
local Tests, DB, Schema, Profiles = PUI.Tests, PUI.DB, PUI.Schema, PUI.Profiles

local function scratch(t, sv)
  local saved = { sv = DB.sv, profile = DB.profile, name = DB.profileName, base = DB.base, baseName = DB.baseName }
  t:cleanup(function()
    DB.sv, DB.profile, DB.profileName, DB.base, DB.baseName = saved.sv, saved.profile, saved.name, saved.base, saved.baseName
    Schema:ApplyAll()
  end)
  return DB:Init(sv)
end

Tests:Add("Profiles", "create, copy (deep), rename and delete", function(t)
  scratch(t, {})
  Schema:Set("sentinel.safeModeThreshold", 9)
  t:eq(Profiles:Create("Raid", "Default"), "Raid", "copy created")
  t:eq(DB.sv.profiles.Raid["sentinel.safeModeThreshold"], 9, "copied value")
  DB.sv.profiles.Raid["sentinel.safeModeThreshold"] = 4
  t:eq(DB.sv.profiles.Default["sentinel.safeModeThreshold"], 9, "no alias (G19)")
  t:ok(not Profiles:Create("Raid"), "duplicate refused")
  t:ok(not Profiles:Create("  "), "empty refused")
  t:ok(not Profiles:Delete("Default"), "active profile not deletable")
  Profiles:MapContent("raid", "Raid")
  t:eq(Profiles:Rename("Raid", "Raid Night"), "Raid Night", "renamed")
  t:eq(Profiles:Mapped("raid"), "Raid Night", "content map follows rename")
  t:ok(Profiles:Delete("Raid Night"), "deleted")
  t:eq(Profiles:Mapped("raid"), nil, "content map cleared")
end)

Tests:Add("Profiles", "export and import round trip, all or nothing", function(t)
  scratch(t, {})
  Schema:Set("sentinel.safeModeThreshold", 7)
  Schema:Set("options.tint", { r = 1, g = 0, b = 0, a = 0.5 })
  local s = Profiles:Export("Default")
  t:ok(s:sub(1, 6) == "!PUI1!", "prefix")
  local plan = assert(Profiles:Decode(s))
  t:eq(plan.count, 2, "two settings")
  t:eq(#plan.invalid, 0, "valid")
  t:eq(Profiles:Apply(plan, "new", "Copy"), "Copy", "imported as new")
  t:eq(DB.sv.profiles.Copy["options.tint"].a, 0.5, "table value kept")
  t:ok(not Profiles:Decode("hello"), "garbage refused")
  t:ok(not Profiles:Decode("!PUI1!@@@@"), "damaged refused")
  -- an invalid value refuses the whole import
  local bad = "!PUI1!" .. C_EncodingUtil.EncodeBase64(C_EncodingUtil.CompressString(Profiles.Serialize({ v = 1, name = "X",
    values = { ["sentinel.safeModeThreshold"] = "lots", ["studio.snap"] = false, ["nope.key"] = 1 } })))
  local p2 = assert(Profiles:Decode(bad))
  t:eq(#p2.invalid, 1, "one invalid")
  t:eq(p2.unknown, 1, "one unknown")
  t:ok(not Profiles:Apply(p2, "merge", "Default"), "refused")
  t:eq(Schema:Get("studio.snap"), true, "nothing changed")
  t:eq(Profiles.Deserialize(Profiles.Serialize({ a = { 1, 2, "x" }, b = true })).a[3], "x", "serializer nested")
end)

Tests:Add("Profiles", "content layer switches by content and stores differences only", function(t)
  scratch(t, {})
  Schema:Set("sentinel.safeModeThreshold", 8)
  Profiles:Create("Arena")
  DB.sv.profiles.Arena["studio.snap"] = false
  Profiles:MapContent("arena", "Arena")
  local was = rawget(_G, "IsInInstance")
  _G.IsInInstance = function() return true, "arena" end
  t:cleanup(function() _G.IsInInstance = was end)
  t:eq(Profiles:Content(), "arena", "content detected")
  Profiles:Evaluate()
  t:eq(DB.profileName, "Arena", "layer active")
  t:eq(Schema:Get("studio.snap"), false, "layer value")
  t:eq(Schema:Get("sentinel.safeModeThreshold"), 8, "base value shows through")
  t:eq(DB.sv.chars[DB:CharKey()], "Default", "character choice untouched")
  Schema:Set("core.autoProfile", false)
  t:cleanup(function() Schema:Set("core.autoProfile", true) end)
  t:eq(DB.profileName, "Default", "auto off returns to own profile")
  Schema:Set("core.autoProfile", true)
  t:eq(DB.profileName, "Arena", "back on")
  local where = Schema:Get("core.autoProfile.where")
  where.switch.arena = false
  Schema:Set("core.autoProfile.where", where)
  t:eq(DB.profileName, "Default", "grid cell off stops the switch")
  _G.IsInInstance = was
end)

Tests:Add("Profiles", "new widget types validate", function(t)
  local d = Schema:Def("options.tint")
  t:ok(Schema:Validate(d, { r = 0, g = 0.5, b = 1, a = 1 }), "colour ok")
  t:ok(not Schema:Validate(d, { r = 2, g = 0, b = 0 }), "colour range")
  local k = Schema:Def("options.toggleKey")
  t:ok(Schema:Validate(k, "CTRL-SHIFT-P"), "key ok")
  t:ok(not Schema:Validate(k, "ctrl p("), "key refused")
  local a = Schema:Def("options.openAnchor")
  t:ok(not Schema:Validate(a, { point = "MIDDLE", x = 0, y = 0 }), "bad point")
  local l = Schema:Def("options.pinned")
  t:ok(not Schema:Validate(l, { "a", "b", "c", "d", "e", "f", "g", "h", "i" }), "max items")
  local g = Schema:Def("core.autoProfile.where")
  t:ok(not Schema:Validate(g, { switch = { moon = true } }), "unknown column")
  t:ok(PUI.OptionsHost.category ~= nil, "registered with Blizzard Settings")
end)
